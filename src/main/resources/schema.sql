CREATE TABLE IF NOT EXISTS task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    biz_request_id VARCHAR NOT NULL UNIQUE,
    user_id VARCHAR,
    amount_cents BIGINT,
    tier VARCHAR,
    status VARCHAR,
    reason VARCHAR,
    created_at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS payment_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES task(id),
    channel_id VARCHAR,
    amount_cents BIGINT,
    status VARCHAR,
    attempts INT NOT NULL DEFAULT 0,
    reason VARCHAR,
    updated_at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS job (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES payment_order(id),
    status VARCHAR NOT NULL,
    created_at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS channel_switch_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT,
    order_id BIGINT,
    from_channel VARCHAR,
    to_channel VARCHAR,
    reason VARCHAR,
    at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS state_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    from_status VARCHAR,
    to_status VARCHAR,
    outcome VARCHAR NOT NULL,
    source VARCHAR NOT NULL,
    at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS callback_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id VARCHAR,
    order_id BIGINT,
    status VARCHAR,
    sequence BIGINT,
    sent_at TIMESTAMP,
    outcome VARCHAR NOT NULL,
    received_at TIMESTAMP
);
ALTER TABLE payment_order ADD COLUMN IF NOT EXISTS submitting_at TIMESTAMP;
ALTER TABLE job ADD COLUMN IF NOT EXISTS started_at TIMESTAMP;
CREATE TABLE IF NOT EXISTS recovery_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    action VARCHAR NOT NULL,
    channel_answer VARCHAR,
    at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS recon_diff (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recon_date DATE NOT NULL,
    type VARCHAR NOT NULL,
    channel_id VARCHAR,
    order_id BIGINT,
    local_amount BIGINT,
    channel_amount BIGINT,
    local_status VARCHAR,
    channel_status VARCHAR,
    created_at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS gateway_call_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id VARCHAR NOT NULL,
    order_id BIGINT NOT NULL,
    accepted BOOLEAN NOT NULL,
    reason VARCHAR,
    duration_ms BIGINT NOT NULL,
    at TIMESTAMP
);
